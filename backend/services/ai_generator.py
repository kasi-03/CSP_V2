import re
from groq import Groq
from config import Config


def get_groq_client():
    """Initialize and return a Groq client instance."""
    api_key = Config.GROQ_API_KEY
    if not api_key:
        raise ValueError("GROQ_API_KEY not found in environment or .env file.")
    return Groq(api_key=api_key)


MODELS = Config.GROQ_MODELS


def clean_ai_output(text: str) -> str:
    """
    Removes AI explanations, markdown, notes,
    and unwanted formatting from LLM responses.
    """
    if not text:
        return ""

    # Remove markdown code blocks
    text = re.sub(r"```.*?```", "", text, flags=re.DOTALL)

    # Remove markdown headings
    text = re.sub(r"^#+\s*.*$", "", text, flags=re.MULTILINE)

    # Remove common AI prefixes
    prefixes = [
        "Here is the complaint:",
        "Here is your complaint:",
        "Here is the translated complaint:",
        "Here is the English complaint:",
        "Complaint:",
        "Translation:",
        "Translated Complaint:",
        "Response:",
        "Output:"
    ]

    for prefix in prefixes:
        text = re.sub(
            rf"^{re.escape(prefix)}\s*",
            "",
            text,
            flags=re.IGNORECASE
        )

    # Remove AI notes
    patterns = [
        r"\(.*?revised.*?\)",
        r"\(.*?paragraph.*?\)",
        r"Note:.*",
        r"Disclaimer:.*",
        r"Explanation:.*",
        r"AI Response:.*",
        r"This response.*",
        r"I have.*",
        r"The complaint.*generated.*",
        r"Generated by.*"
    ]

    for pattern in patterns:
        text = re.sub(
            pattern,
            "",
            text,
            flags=re.IGNORECASE | re.DOTALL
        )

    # Remove excessive blank lines
    text = re.sub(r"\n{3,}", "\n\n", text)

    # Remove trailing spaces
    text = "\n".join(line.rstrip() for line in text.splitlines())

    return text.strip()


def call_llm(prompt: str) -> str:
    """
    Send prompt to Groq LLM across configured models with fallback.
    Never prints or exposes secret API keys.
    """
    client = get_groq_client()
    last_error = None

    for model in MODELS:
        try:
            response = client.chat.completions.create(
                model=model,
                temperature=0.2,
                messages=[
                    {
                        "role": "user",
                        "content": prompt
                    }
                ]
            )
            output = response.choices[0].message.content
            return clean_ai_output(output)
        except Exception as e:
            last_error = e
            continue

    if last_error:
        raise last_error
    raise RuntimeError("No Groq model was able to produce a response.")


def clean_speech(text: str) -> str:
    """Clean conversational Telugu speech recognition text."""
    prompt = f"""
You are an expert Telugu language assistant.

The following text was generated from speech recognition.

Your job is to:

- Correct obvious speech recognition mistakes.
- Use surrounding context to determine the most likely intended meaning.
- Fix incorrect words caused by accent, pronunciation, or transcription errors.
- Preserve the intended names, locations, dates, times, phone numbers and vehicle numbers.
- Correct obvious speech recognition errors inside these entities when the intended value is clear from context.
- Never invent or guess unknown names.
- If a phrase is obviously incorrect due to speech recognition, replace it only when the intended meaning is clear from the surrounding context. Otherwise leave it unchanged.
- Fix broken words.
- Fix incomplete phrases.
- Preserve the original meaning.
- Do not invent new facts.
- Do not add information.
- Do not convert it into a complaint.
- Return clean conversational Telugu exactly as the speaker intended, while preserving the spoken style.
- Do not convert it into formal complaint language.

Return only the corrected speech text.

Speech:

{text}
"""
    return call_llm(prompt)


